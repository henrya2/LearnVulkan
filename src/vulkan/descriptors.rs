pub fn create_descriptor_pool(device: &ash::Device, num_materials: u32) -> vk::DescriptorPool {
    let frames = 2u32;
    let mut sizes = Vec::new();
    sizes.push(vk::DescriptorPoolSize {
        ty: vk::DescriptorType::UNIFORM_BUFFER,
        descriptor_count: frames * 2,
    });
    let sampler_count = num_materials * 5 + frames * 4;
    if sampler_count > 0 {
        sizes.push(vk::DescriptorPoolSize {
            ty: vk::DescriptorType::COMBINED_IMAGE_SAMPLER,
            descriptor_count: sampler_count,
        });
    }
    let info = vk::DescriptorPoolCreateInfo::default()
        .pool_sizes(&sizes)
        .max_sets(frames + num_materials);
    unsafe { device.create_descriptor_pool(&info, None).unwrap() }
}
